'use strict';
/**
 * PostgreSQL access layer: pooled connections (TLS), versioned migrations, transactions.
 *
 * Config (any one of):
 *   DATABASE_URL=postgresql://user:pass@host:5432/db?sslmode=require
 *   or the standard PGHOST / PGPORT / PGUSER / PGPASSWORD / PGDATABASE variables.
 * Optional: DB_SCHEMA (isolated schema, used by the tests), DB_POOL_MAX, PGSSLMODE=disable (local dev only).
 */
const { Pool, types } = require('pg');

types.setTypeParser(20, v => Number(v)); // BIGINT → number (timestamps are epoch milliseconds, well inside 2^53)

const SCHEMA = process.env.DB_SCHEMA || '';
if (SCHEMA && !/^[a-z_][a-z0-9_]*$/.test(SCHEMA)) throw new Error('DB_SCHEMA must match [a-z_][a-z0-9_]*');

function sslFor(url) {
  let mode = (process.env.PGSSLMODE || '').toLowerCase();
  let host = process.env.PGHOST || '';
  if (url) { try { const u = new URL(url); mode = (u.searchParams.get('sslmode') || mode).toLowerCase(); host = u.hostname; } catch { /* keep env */ } }
  if (mode === 'disable' || host === 'localhost' || host === '127.0.0.1') return false;
  return { rejectUnauthorized: true };
}

const url = process.env.DATABASE_URL || '';
if (!url && !process.env.PGHOST) throw new Error('Database is not configured: set DATABASE_URL (or PGHOST/PGUSER/PGPASSWORD/PGDATABASE).');

const cfg = {
  max: +process.env.DB_POOL_MAX || (process.env.VERCEL ? 3 : 10), // many short-lived instances share one server: keep each pool small
  idleTimeoutMillis: process.env.VERCEL ? 5e3 : 30e3,
  connectionTimeoutMillis: 10e3,
  statement_timeout: 15e3,
  idle_in_transaction_session_timeout: 30e3,
  keepAlive: true,
  application_name: 'sjbc',
  ssl: sslFor(url),
};
if (url) cfg.connectionString = url.replace(/[?&]sslmode=[^&]*/g, m => (m.startsWith('?') ? '?' : '')).replace(/\?$/, '');
const pool = new Pool(cfg);
pool.on('error', e => console.error('[db] idle client error:', e.message));
if (SCHEMA) pool.on('connect', c => { c.query(`SET search_path TO "${SCHEMA}"`).catch(() => {}); });

/* ------------------------------------------------------------- migrations */
// Append-only. Each entry runs once, in order, inside a transaction.
const MIGRATIONS = [
  {
    id: 1, name: 'initial schema',
    sql: `
      CREATE TABLE users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        email TEXT NOT NULL UNIQUE,
        name TEXT NOT NULL DEFAULT '',
        picture TEXT NOT NULL DEFAULT '',
        google_sub TEXT,
        role TEXT NOT NULL DEFAULT 'pending' CHECK (role IN ('pending','editor','admin','blocked')),
        created_at BIGINT NOT NULL,
        last_login BIGINT
      );
      CREATE TABLE sessions (
        id TEXT PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        expires_at BIGINT NOT NULL
      );
      CREATE INDEX idx_sessions_exp ON sessions(expires_at);
      CREATE INDEX idx_sessions_user ON sessions(user_id);
      CREATE TABLE tournaments (
        id TEXT PRIMARY KEY,
        data JSONB NOT NULL,
        version INTEGER NOT NULL DEFAULT 1,
        created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
        created_at BIGINT NOT NULL,
        updated_at BIGINT NOT NULL
      );
      CREATE INDEX idx_tournaments_created ON tournaments(created_at DESC);
      CREATE INDEX idx_tournaments_owner ON tournaments(created_by);
    `,
  },
];

async function migrate() {
  const c = await pool.connect();
  try {
    if (SCHEMA) { await c.query(`CREATE SCHEMA IF NOT EXISTS "${SCHEMA}"`); await c.query(`SET search_path TO "${SCHEMA}"`); }
    await c.query('SELECT pg_advisory_lock(727401)'); // several instances may boot at once
    try {
      await c.query('CREATE TABLE IF NOT EXISTS schema_migrations (id INTEGER PRIMARY KEY, name TEXT NOT NULL, applied_at BIGINT NOT NULL)');
      const done = new Set((await c.query('SELECT id FROM schema_migrations')).rows.map(r => r.id));
      for (const m of MIGRATIONS.filter(x => !done.has(x.id))) {
        await c.query('BEGIN');
        try {
          await c.query(m.sql);
          await c.query('INSERT INTO schema_migrations (id, name, applied_at) VALUES ($1,$2,$3)', [m.id, m.name, Date.now()]);
          await c.query('COMMIT');
          console.log(`[db] applied migration ${m.id}: ${m.name}`);
        } catch (e) { await c.query('ROLLBACK'); throw e; }
      }
    } finally { await c.query('SELECT pg_advisory_unlock(727401)'); }
  } finally { c.release(); }
}

/* ---------------------------------------------------------------- helpers */
const query = (text, params) => pool.query(text, params);
const one = async (text, params) => (await pool.query(text, params)).rows[0] || null;
const many = async (text, params) => (await pool.query(text, params)).rows;

/** Run fn(client) in a transaction; commits on return, rolls back on throw. */
async function tx(fn) {
  const c = await pool.connect();
  try {
    await c.query('BEGIN');
    const r = await fn(c);
    await c.query('COMMIT');
    return r;
  } catch (e) {
    await c.query('ROLLBACK').catch(() => {});
    throw e;
  } finally { c.release(); }
}

/** A dedicated connection for LISTEN/NOTIFY (cannot come from the pool). */
async function listenerClient() {
  const { Client } = require('pg');
  const c = new Client({ ...cfg, statement_timeout: 0, idle_in_transaction_session_timeout: 0 });
  await c.connect();
  if (SCHEMA) await c.query(`SET search_path TO "${SCHEMA}"`);
  return c;
}

module.exports = { pool, migrate, query, one, many, tx, listenerClient, SCHEMA };
